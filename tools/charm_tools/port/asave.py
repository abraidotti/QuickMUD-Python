"""charm_tools port asave: save the whole stock world with OLC's asave on both games and compare every file (#91).

A builder (the fixture Planner, security 9, so every stock area is his to save) logs in and types "asave world";
then each file in area.lst, and area.lst itself, is read back with the scenario harness's @file. Both games play
the same generated scenario (tools/oracle/scenario.c in the build-stage image, and charm.testing.scenario), so this
is port scenarios with a golden too big to keep: about 3 MB, and one byte off would fail one huge diff.

    python -m charm_tools port asave --docker charm:build
    python -m charm_tools port asave --docker charm:build --only midgaard
"""

from __future__ import annotations

import re

from ..paths import find_root
from .scenarios import c_play, difference, py_play

LOGIN = ["@connect b", "Planner", "smoke123", "@return", "@return"]
FILE_LINE = re.compile(r'^file (\S+) (.*)$')


def area_files(root) -> list[str]:
    words = (root / "area" / "area.lst").read_text(encoding="latin-1").split()
    return [w for w in words if not w.startswith("$")]


def scenario(files: list[str]) -> str:
    return "\n".join(["# generated by charm_tools port asave"] + LOGIN + ["asave world", "@file area.lst"]
                     + [f"@file {f}" for f in files]) + "\n"


def files_in(lines: list[str]) -> dict[str, str]:
    return {m.group(1): m.group(2) for m in map(FILE_LINE.match, lines) if m}


def first_difference(a: str, b: str) -> str:
    """Where two escaped files first differ, with some of each around it."""
    i = next((k for k in range(min(len(a), len(b))) if a[k] != b[k]), min(len(a), len(b)))
    lo = max(0, i - 60)
    line = a[:i].count("\\n") + 1
    return (f"line {line}, at escaped character {i}:\n      C:      ...{a[lo:i + 60]}\n"
            f"      Python: ...{b[lo:i + 60]}")


def run(image: str, only: str | None = None) -> int:
    root = find_root()
    files = area_files(root)
    if only:
        files = [f for f in files if only.lower() in f.lower()]
    text = scenario(files)
    print(f"asave world, then {len(files) + 1} files read back, on both games", flush=True)
    c = c_play(image, text, root)
    py = py_play(text, root)
    c_files, py_files = files_in(c), files_in(py)
    failed = 0
    for name in ["area.lst"] + files:
        a, b = c_files.get(name), py_files.get(name)
        if a is None or b is None:
            print(f"MISSING   {name}: {'C' if a is None else 'Python'} printed no file line")
            failed += 1
        elif a != b:
            print(f"DIFFERENT {name}: {first_difference(a, b)}")
            failed += 1
        else:
            size = len(a) - 2
            print(f"SAME      {name} ({'missing on both' if a == 'missing' else f'{size} escaped characters'})")
    # The rest of the output (the login, "You saved the world.", the log lines) must match too.
    rest = difference([x for x in c if not x.startswith("file ")], [x for x in py if not x.startswith("file ")],
                      text)
    if rest:
        print(f"DIFFERENT the session: {rest}")
        failed += 1
    print("every file the same" if not failed else f"{failed} difference(s)")
    return 1 if failed else 0
