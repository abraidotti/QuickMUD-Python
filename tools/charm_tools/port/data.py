INT_TYPES = {"int", "sh_int", "long", "bool", "unsigned int", "long int"}
STRUCT_SOURCES = ("merc.h", "special.c", "tables.h", "magic.h", "interp.h", "board.h")
DEFINE_SOURCES = ("merc.h", "board.h")  # the headers whose #defines go in constants.py


@dataclass(frozen=True)
class Field:
    ctype: str  # e.g. "char *", "sh_int", "SPEC_FUN *"
    name: str
    kind: str  # "str", "int", "bool", or "ref" (a pointer to a function or a variable: kept as its C name)
    length: int | None  # array length, or None

    def py_type(self) -> str:
        base = {"str": "str | None", "int": "int", "bool": "bool", "ref": "str | None"}[self.kind]
        return f"tuple[{base.split(' |')[0]}, ...]" if self.length is not None else base


DECL = re.compile(r"^(?P<type>(?:const\s+|unsigned\s+)?[A-Za-z_]\w*)\s*(?P<ptr>\*?)\s*(?:const\s+)?(?P<name>[A-Za-z_]\w*)"
                  r"\s*(?:\[(?P<len>[^\]]+)\])?$")


def struct_fields(src: Path, defines: Defines, struct: str) -> list[Field]:
    for name in STRUCT_SOURCES:
        path = src / name
        if not path.exists():
            continue
        text = _strip_comments(path.read_text(encoding="latin-1"))
        m = re.search(rf"^struct\s+{struct}\s*\{{(.*?)^\}};", text, re.S | re.M)
        if m:
            break
    else:
        raise SourceError(f"no 'struct {struct} {{' in {', '.join(STRUCT_SOURCES)}")
    fields = []
    for decl in (d.strip() for d in m.group(1).split(";")):
        if not decl:
            continue
        d = DECL.match(" ".join(decl.split()))
        if not d:
            raise SourceError(f"struct {struct}: can't read field {decl!r}")
        ctype = d.group("type").replace("const ", "")
        ptr = bool(d.group("ptr"))
        char_array = ctype == "char" and not ptr and d.group("len")
        if (ctype == "char" and ptr) or char_array:
            kind = "str"  # a char * or a char [N] initialised with a string literal
        elif ptr:
            kind = "ref"
        elif ctype == "bool":
            kind = "bool"
        elif ctype in INT_TYPES:
            kind = "int"
        else:
            raise SourceError(f"struct {struct}: field {d.group('name')} has type {ctype!r}, which isn't handled")
        length = None
        if d.group("len") and not char_array:
            length = int(d.group("len")) if d.group("len").isdigit() else defines[d.group("len")]
        ctype_note = f"char [{d.group('len')}]" if char_array else ctype + (" *" if ptr else "")
        fields.append(Field(ctype_note, d.group("name"), kind, length))
    return fields


def value(field: Field, raw, defines: Defines, where: str):
    """One C initialiser value, as Python, for a field of this kind."""
    if field.kind == "str":
        if raw == "NULL":
            return None
        if isinstance(raw, Str):
            return raw.value
        raise SourceError(f"{where}: {field.name} should be a string, got {raw!r}")
    if field.kind == "ref":
        if raw in ("NULL", "0"):  # a null pointer (skill_table's "reserved" row writes 0)
            return None
        name = raw[1:].strip() if raw.startswith("&") else raw
        if not re.fullmatch(r"[A-Za-z_]\w*", name):
            raise SourceError(f"{where}: {field.name} should name a function or variable, got {raw!r}")
        return name
    if isinstance(raw, Str):
        raise SourceError(f"{where}: {field.name} should be a number, got a string")
    number = defines._eval(raw, (f"{where} {field.name}",))
    return bool(number) if field.kind == "bool" else number


IDENTITY_MACRO = re.compile(r"^#define\s+(\w+)\s*\(\s*(\w+)\s*\)\s+\(?\s*\2\s*\)?\s*$", re.M)


def identity_macros(path: Path) -> set[str]:
    """Function-like macros in a C file that expand to their argument, like const.c's ``#define SLOT(n) n``."""
    return {m.group(1) for m in IDENTITY_MACRO.finditer(path.read_text(encoding="latin-1"))}


def expand(raw, macros: set[str]):
    """``SLOT (70)`` -> ``70`` for an identity macro; anything else unchanged."""
    if isinstance(raw, str) and not isinstance(raw, Str):
        m = re.fullmatch(r"(\w+)\s*\((.*)\)", raw.strip(), re.S)
        if m and m.group(1) in macros:
            return m.group(2).strip()
    return raw


def rows(src: Path, defines: Defines, table: Table, fields: list[Field]) -> list[dict]:
    entries = read_array(src / table.c_file, table.c_name)
    macros = identity_macros(src / table.c_file)
    # A table that ends with a sentinel row (every string field NULL: {NULL, 0, ...} or item_table's {0, NULL}) is
    # scanned up to it in C, so it isn't a row here.
    strings = [i for i, f in enumerate(fields) if f.kind == "str" and f.length is None]
    if entries and strings and all(i < len(entries[-1]) and entries[-1][i] == "NULL" for i in strings):
        entries = entries[:-1]
    elif table.empty_sentinel:
        if not (entries and isinstance(entries[-1][0], Str) and entries[-1][0].value == ""):
            raise SourceError(f"{table.c_file} {table.c_name}: no closing row with an empty name")
        entries = entries[:-1]
    out = []
    for n, entry in enumerate(entries):
        where = f"{table.c_file} {table.c_name}[{n}]"
        if len(entry) > len(fields):
            raise SourceError(f"{where}: {len(entry)} values for {len(fields)} fields")
        # C zero-fills the fields a row leaves out (skill_table's spells often stop before msg_obj).
        entry = [expand(e, macros) for e in entry] + ["NULL" if f.kind in ("str", "ref") else "0"
                                                      for f in fields[len(entry):]]
        row = {}
        for f, raw in zip(fields, entry):
            if f.length is not None:
                if not (isinstance(raw, str) and raw.startswith("{")):
                    raise SourceError(f"{where}: {f.name} should be {{...}}, got {raw!r}")
                items = _split_top(raw[1:-1])
                if len(items) > f.length:
                    raise SourceError(f"{where}: {f.name} has {len(items)} values for {f.length}")
                vals = [value(f, _as_field(i), defines, where) for i in items]
                vals += [0 if f.kind == "int" else None] * (f.length - len(vals))  # C zero-fills the rest
                row[f.name] = tuple(vals)
            else:
                row[f.name] = value(f, raw, defines, where)
        out.append(row)
    return out


def _as_field(text: str):
    if text.startswith('"') and text.endswith('"'):
        return Str(c_unescape(text[1:-1]))
    return text


def class_name(struct: str) -> str:
    return "".join(p.capitalize() for p in struct.split("_"))


def py(v) -> str:
    if isinstance(v, str):
        return json.dumps(v)
    if isinstance(v, tuple):
        return "(" + ", ".join(py(x) for x in v) + ("," if len(v) == 1 else "") + ")"
    return repr(v)


def docstring(title: str, sources: list[str], extra: str = "") -> str:
    body = f"{title}\n\n{REGENERATE}\n"
    if extra:
        body += "\n" + "\n".join(wrap(extra)) + "\n"
    ported = ", ".join(f"src/{s}" for s in sources)
    return f'"""{body}\n{CREDIT} Ported from {ported}. {POINTER}\n"""\n'


def wrap(text: str, width: int = 116) -> list[str]:
    words, lines, line = text.split(), [], ""
    for w in words:
        if line and len(line) + 1 + len(w) > width:
            lines.append(line)
            line = w
        else:
            line = f"{line} {w}" if line else w
    return lines + ([line] if line else [])


def generate(root: Path | None = None) -> dict[str, str]:
    """{path under game/charm/data: file text} for every generated module."""
    root = root or find_root()
    src = src_dir(root)
    defines = Defines(*(src / name for name in DEFINE_SOURCES))
    files: dict[str, str] = {}

    # Structs, in first-use order.
    structs: dict[str, list[Field]] = {}
    for t in TABLES:
        if t.struct not in structs:
            structs[t.struct] = struct_fields(src, defines, t.struct)
    out = [docstring("The C game's table structs, as frozen dataclasses with the C field names.",
                     ["merc.h"], "A field that points to a function or a variable (a spec_fun, a gsn) holds its "
                     "C name as a string until that code is ported."),
           "from dataclasses import dataclass\n"]
    for struct, fields in structs.items():
        out.append(f"\n\n@dataclass(frozen=True)\nclass {class_name(struct)}:\n    \"\"\"struct {struct}\"\"\"\n\n")
        for f in fields:
            note = f"  # C: {f.ctype}{f' [{f.length}]' if f.length is not None else ''}"
            out.append(f"    {f.name}: {f.py_type()}{note}\n")
    files["structs.py"] = "\n".join(out[:2]) + "".join(out[2:])

    # Constants: every #define in merc.h that's a number or a single string literal, in file order.
    lines = []
    for name in defines.names:
        if re.fullmatch(r"[A-Za-z]{1,2}", name):  # the flag letters A..Z, aa..ee: bit helpers, not names
            continue
        raw = defines.raw[name]
        if re.fullmatch(r'"(?:[^"\\]|\\.)*"', raw):
            lines.append(f"{name} = {json.dumps(c_unescape(raw[1:-1]))}")
            continue
        try:
            lines.append(f"{name} = {defines[name]}")
        except SourceError:
            continue
    files["constants.py"] = (docstring("The C game's #define constants from merc.h and board.h: every one that's a "
                                       "number or a plain string.", list(DEFINE_SOURCES),
                                       "The flag letters (#define A 1 ... #define ee 1073741824) are left out; "
                                       "values that use them are already worked out here.")
                             + "\n" + "\n".join(lines) + "\n")

    # Tables, grouped into modules.
    modules: dict[str, list[Table]] = {}
    for t in TABLES:
        modules.setdefault(t.module, []).append(t)
    for module, tables in modules.items():
        sources = sorted({t.c_file for t in tables} | {a[0] for a in STRING_ARRAYS if a[3] == module})
        names = ", ".join(f"{t.c_name} ({t.c_file})" for t in tables)
        extra = (f"Tables: {names}. A C table that ends with a NULL sentinel row is scanned up to it; that row "
                 f"isn't here.")
        if any(t.empty_sentinel for t in tables):
            extra = (f"Tables: {names}. The C scans the table up to its closing row, whose name is empty; that row "
                     f"isn't here.")
        parts = [docstring(MODULE_TITLES[module], sources, extra),
                 "from charm.data.structs import " + ", ".join(sorted({class_name(t.struct) for t in tables})) + "\n"]
        for t in tables:
            fields = structs[t.struct]
            cls = class_name(t.struct)
            body = []
            table_defines = Defines(*(src / n for n in DEFINE_SOURCES + t.headers)) if t.headers else defines
            for row in rows(src, table_defines, t, fields):
                args = ", ".join(f"{k}={py(v)}" for k, v in row.items())
                one = f"    {cls}({args}),"
                if len(one) <= 120:
                    body.append(one)
                else:
                    body.append(f"    {cls}(")
                    body += [f"        {k}={py(v)}," for k, v in row.items()]
                    body.append("    ),")
            parts.append(f"\n# {t.c_name}, {t.c_file}\n{t.c_name.upper()} = (\n" + "\n".join(body) + "\n)\n")
        for c_file, c_name, depth, mod in STRING_ARRAYS:
            if mod == module:
                parts.append(f"\n# {c_name}, {c_file}\n{c_name.upper()} = "
                             + py(string_array(src, c_file, c_name, depth)) + "\n")
        files[f"{module}.py"] = parts[0] + "\n" + "".join(parts[1:])
    return files


def string_array(src: Path, c_file: str, c_name: str, depth: int):
    """A nested array of string literals, as nested tuples: title_table[class] -> ((male, female), ...)."""
    def nest(raw, level):
        if level == 0:
            if not (isinstance(raw, str) and raw.startswith('"') and raw.endswith('"')):
                raise SourceError(f"{c_file} {c_name}: expected a string, got {raw!r}")
            return c_unescape(raw[1:-1])
        if not (isinstance(raw, str) and raw.startswith("{")):
            raise SourceError(f"{c_file} {c_name}: expected {{...}}, got {raw!r}")
        return tuple(nest(x, level - 1) for x in _split_top(raw[1:-1]))
    rows = read_array(src / c_file, c_name)
    return tuple(tuple(nest(x if not isinstance(x, Str) else '"' + x.value + '"', depth - 1) for x in row)
                 for row in rows)


def run(check: bool) -> int:
    root = find_root()
    out = game_dir(root) / "charm" / "data"
    files = generate(root)
    stale = [name for name, text in files.items()
             if not (out / name).exists() or (out / name).read_text(encoding="utf-8") != text]
    if check:
        for name in stale:
            print(f"  out of date  game/charm/data/{name}")
        print("data is up to date" if not stale else f"{len(stale)} file(s) would change: run port data")
        return 1 if stale else 0
    out.mkdir(parents=True, exist_ok=True)
    for name in stale:
        (out / name).write_text(files[name], encoding="utf-8", newline="\n")
        print(f"  wrote  game/charm/data/{name}")
    print(f"{len(files)} files, {len(stale)} changed")
    return 0
