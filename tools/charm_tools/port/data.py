"""charm_tools port data: generate the Python game's static tables (game/charm/data/) from the C source.

The C game's tables are positional initialisers in const.c, tables.c and special.c, typed by structs in merc.h. This
reads each struct's fields, each table's rows, and every #define in merc.h that's a number or a plain string, and
writes them out as Python: one frozen dataclass per struct (data/structs.py), the constants (data/constants.py), and
the tables grouped by topic. The readers are narrow and fail loudly: a field or value they don't understand raises
SourceError rather than being guessed. The generated files are committed; --check fails if regenerating would change
them, and the tools' tests run that check.

The C game stays the source until cut-over (plans/python-port.md), so the tables are changed in C and regenerated.
"""

